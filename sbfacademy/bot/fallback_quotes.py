def for_date(d: date | None = None) -> tuple[str, str]:
    """Цитата дня: по номеру дня с начала эпохи — без повторов, пока пул не пройден."""
    d = d or date.today()
    return QUOTES[d.toordinal() % len(QUOTES)]


def message(tagline_html: str, d: date | None = None) -> str:
    text, author = for_date(d)
    return (
        "📈 <b>Мысль дня</b>\n\n"
        f"«{html.escape(text)}»\n"
        f"— {html.escape(author)}\n\n"
        f"<i>{tagline_html}</i>"
    )
